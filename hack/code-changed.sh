#!/bin/sh
# Classify a changed-path list for the PR pipeline: prints `true` when at least
# one path can reach the product (Go, charts, images, build inputs, workflows)
# and `false` when every path is documentation or repository metadata.
#
# This is the single source of truth for the docs-only gate: pull-requests.yaml
# `plan` feeds it the merge diff and e2e-fork.yaml `resolve` feeds it the
# base-repo PR file list. A rename must appear as BOTH paths (git diff
# --no-renames, or filename + previous_filename), so a packages/... -> docs/...
# move still reads as code. A blank line reads as code: fail closed.
#
# Non-code: the docs/ tree, Markdown anywhere, images, LICENSE, GitHub and
# review-bot metadata. Chart README.md files are generated by `make generate`
# (pre-commit re-runs it on every PR) and contract-tested by hack/*.bats, which
# the docs-only lane of the `checks` job still runs, so they need no build or
# e2e. The paths-ignore lists in build-main.yaml, build-release.yaml and
# codeql.yml mirror this pattern; hack/code-changed_test.bats keeps them in step.
set -eu

if [ "$#" -ne 1 ] || [ ! -f "$1" ] || [ ! -r "$1" ]; then
  echo "usage: code-changed.sh <readable-changed-files>" >&2
  exit 2
fi

non_code_pattern='^(docs/|img/|\.gemini/|\.github/ISSUE_TEMPLATE/|\.github/(CODEOWNERS|PULL_REQUEST_TEMPLATE\.md|labels\.yml|renovate\.json)$|\.coderabbit\.yaml$|security-insights\.yml$|LICENSE$|.*\.md$)'

if grep -qvE "$non_code_pattern" "$1"; then
  printf 'true\n'
else
  status=$?
  if [ "$status" -ne 1 ]; then
    exit "$status"
  fi
  printf 'false\n'
fi
